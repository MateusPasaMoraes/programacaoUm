package exercicios;

import java.util.Scanner;

public class Exercicio3 {

	public static void main(String[] args) {
		Scanner sc = new Scanner(System.in);

		int numA = 10, numB = 5;

		System.out.println((numA + numB));
		System.out.println((numA - numB));
		System.out.println((numA * numB));
		System.out.println((numA / numB));
		System.out.println((numA % numB));

		sc.close();
	}

}
